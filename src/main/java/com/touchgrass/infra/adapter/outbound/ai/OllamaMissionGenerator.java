package com.touchgrass.infra.adapter.outbound.ai;

import com.touchgrass.domain.model.Difficulty;
import com.touchgrass.domain.model.GeneratedMissionContent;
import com.touchgrass.domain.port.MissionGenerator;
import org.springframework.stereotype.Component;
import org.springframework.web.client.RestClient;
import tools.jackson.core.JacksonException;
import tools.jackson.databind.ObjectMapper;


import java.util.HashMap;
import java.util.Map;

@Component
public class OllamaMissionGenerator implements MissionGenerator {

    @Override
    public GeneratedMissionContent generate(int maxDurationMinutes, Difficulty difficulty) {
        Map<String, Object> request = new HashMap<>();
        request.put("model", "qwen3:4b-q4_K_M");
        request.put("stream", false);
        request.put("prompt", "Generate an outdoor mission, with a humorous and fun text to lift the mood, respect the time limit of Max Duration Minutes and also base the mission on the chosen Difficulty.\n" +
                "\n" + "Max Duration Minutes: " + maxDurationMinutes + "\n" + "Difficulty: " + difficulty + "\n" +
                "Return only a valid JSON, with the following fields (title, message, activity, durationMinutes, difficulty).\n" +
                "\n" +
                "Use the following JSON as EXAMPLE: \"title\": \"...\",\n" +
                "\"message\": \"...\",\n" +
                "\"activity\": \"...\",\n" +
                "\"durationMinutes\": 10,\n" +
                "\"difficulty\": \"EASY\"" + "durationMinutes must be an integer, greater than zero and less than or equal to maxDurationMinutes.\n" +
                "\n" +
                "difficulty must be exactly one of these values: EASY, MEDIUM, or HARD."
        );

        ObjectMapper objectMapper = new ObjectMapper();

        Map response = restClient
                .post()
                .uri("/api/generate")
                .body(request)
                .retrieve()
                .body(Map.class);

        String missionJson = (String) response.get("response");

        try {
            return objectMapper.readValue(missionJson, GeneratedMissionContent.class);
        } catch (JacksonException exception) {
            throw new RuntimeException("Failed to parse mission generated by Ollama", exception);
        }

    }

        private RestClient restClient;



    public OllamaMissionGenerator(RestClient restClient) {
            this.restClient = restClient;
        }
    }

